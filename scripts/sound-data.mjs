// Writes the recordings in sounds/ into src/sounds/*.ts as data: URLs.
//
//   npm run sounds
//
// The page never requests an audio file: download managers (IDM and the
// like) grab every .mp3, .ogg or .wav a page fetches and offer to save them
// all, one after another. As data inside scripts (gzipped on the wire to
// about the files' own size) they are only ever scripts.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const data = (name) => `data:audio/mpeg;base64,${readFileSync(`${root}sounds/${name}.mp3`).toString('base64')}`
const header = (what) => `// Generated by scripts/sound-data.mjs from sounds/*.mp3 — don't edit. ${what}\n`

const effects = ['cry', 'rip', 'crinkle', 'pump', 'squeal', 'hiss', 'latex', 'water']
writeFileSync(
  `${root}src/sounds/effects.ts`,
  header('The film\'s recordings (CC0, Freesound: see the footer), loaded when sound may be wanted.') + effects.map((n) => `export const ${n} = '${data(n)}'\n`).join(''),
)
writeFileSync(
  `${root}src/sounds/music.ts`,
  header('24 bars of «SexyJazzLooper» by BaDoink (CC0, Freesound) plus a second of tail for the cross-fade, loaded once sound is on.') + `export const music = '${data('music')}'\n`,
)
console.log(`src/sounds: ${effects.length} effects and the music, as data`)
